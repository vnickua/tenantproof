const params = new URLSearchParams(window.location.search);
const locale = params.get("lang") === "uk" ? "uk" : "en";
const selected = copy[locale];
document.documentElement.lang = locale === "uk" ? "uk" : "en";
document.title = selected.title;
const description = document.querySelector('meta[name="description"]');
if (description) description.setAttribute("content", selected.description);

document.querySelectorAll("[data-i18n]").forEach((node) => {
  const key = node.dataset.i18n;
  if (selected[key]) node.textContent = selected[key];
});
document.querySelectorAll("[data-i18n-html]").forEach((node) => {
  const key = node.dataset.i18nHtml;
  if (selected[key]) node.innerHTML = selected[key];
});
document.querySelectorAll("[data-locale-link]").forEach((link) => {
  const isCurrent = link.dataset.localeLink === locale;
  if (isCurrent) link.setAttribute("aria-current", "page");
  else link.removeAttribute("aria-current");
});
if (locale === "uk") {
  document.querySelectorAll("[data-locale-src-uk]").forEach((image) => {
    image.setAttribute("src", image.dataset.localeSrcUk);
  });
}
